        <li><strong>Messages</strong>: your name, email address and message when you use our contact form.</li>
        <li><strong>Technical information</strong>: a session cookie that keeps you signed in and remembers your cart, and standard server logs (such as IP address and browser type) used for security and troubleshooting.</li>
      </ul>

      <h4>How we use your information</h4>
      <ul>
        <li>To prepare, deliver and confirm your orders and reservations.</li>
        <li>To contact you about your order, reservation or enquiry.</li>
        <li>To manage your account and let you sign in.</li>
        <li>To keep the website secure and working properly.</li>
        <li>To meet our legal, tax and accounting obligations.</li>
      </ul>
      <p>We do not sell your personal information, and we do not use it for advertising.</p>

      <h4>Who we share it with</h4>
      <p>
        Your information is used by Tawhay staff who need it to serve you. We share it only with service providers that
        help us run the website, such as our hosting and email providers, and only as needed to provide those services.
        If you pay online, your payment is handled by the payment provider and we do not store your card details.
        We may also disclose information when required by law.
      </p>

      <h4>How long we keep it</h4>
      <p>
        We keep account information while your account is active. Order and payment records are kept for as long as
        required for accounting and tax purposes. Reservation and contact-form details are kept only as long as needed
        to handle your request.
      </p>

      <h4>Your rights</h4>
      <p>
        You may ask to see, correct or delete the personal information we hold about you, or object to how we use it.
        You may also file a complaint with the National Privacy Commission (privacy.gov.ph).
      </p>

